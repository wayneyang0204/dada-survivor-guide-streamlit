def normalize(text: str) -> str:
    value = unicodedata.normalize("NFKC", text).casefold()
    for old, new in (("自定", "自訂"), ("爆擊", "暴擊"), ("魁儡", "傀儡"), ("维纳托", "維納托")):
        value = value.replace(old, new)
    return re.sub(r"\s+", " ", value).strip()


